('Install-dir','Каталог версионного приложения и комплектной JVM. Его замена должна согласовываться с миграциями постоянных данных.'),
('Data-dir','Каталог постоянного состояния Nexus: DB, настройки и типично blobs/журналы. Не удаляется при обычном завершении занятия.'),
