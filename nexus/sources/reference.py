('Revalidation','Повторная проверка актуальности сохранённого содержимого у upstream. Возможна без повторной передачи полного тела, если протокол это поддерживает.'),
('Negative cache','Кэш знания об отсутствии ресурса. Уже появившаяся upstream версия может оставаться невидимой до TTL либо контролируемой invalidation.'),
