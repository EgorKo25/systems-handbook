('Invalidation','Признание кэшированного знания просроченным для последующей проверки. Не обязательно удаляет все физические bytes и не скачивает весь upstream сразу.'),
('HTTP','Hypertext Transfer Protocol — прикладной протокол запросов/ответов с методами, адресами, заголовками и статусом. Успех транспорта не равен проверке бизнес-содержимого.'),
