def flag(name, action, when, example, result):
    return dict(flag=name, action=action, when=when, example=example, result=result)


def command(name, purpose, syntax, chapter, url, flags=(), situations=(), aliases=()):
    return dict(name=name, aliases=list(aliases), purpose=purpose, syntax=syntax,
                chapter=chapter, volume='nexus', source=url,
                sources=[dict(title='Первичный источник', url=url)],
                flags=list(flags), situations=list(situations))


