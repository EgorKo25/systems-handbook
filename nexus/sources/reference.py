('Reverse proxy','Входной HTTP посредник перед Nexus, например NGINX. Передаёт маршрут/заголовки и может завершать TLS, ограничивать body и timeout.'),
('Endpoint','Адрес и интерфейс обращения. Открытый TCP порт, успешный HTTP probe и удачное чтение asset — разные уровни свидетельств.'),
