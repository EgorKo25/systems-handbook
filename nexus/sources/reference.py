('Community Edition · CE','Бинарная редакция Sonatype Nexus Repository с доступными форматами и операционными ограничениями. Для 3.97.3 учтены usage limits и обязательная base telemetry.'),
('Nexus Repository Core','Открытое исходное дерево с собственным составом форматов. Сборка Core не равна полной бинарной Community Edition.'),
