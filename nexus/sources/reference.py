('Артефакт · artifact','Сохранённый результат или вход разработки: исходный пакет, бинарник, образ, manifest. Его идентичность определяется форматом и точными байтами.'),
('Coordinate','Координата содержимого по правилам формата, например module path + version у Go. Не обязательно совпадает с физическим именем файла blob store.'),
