('Asset','Адресуемый ресурс репозитория, например конкретный ZIP или go.mod. Metadata связывает его с физическим blob.'),
('Blob','Сохранённый двоичный объект с внутренней идентичностью. Ручное копирование файла в blobs не создаёт корректную публикацию.'),
('Blob store','Backend хранения содержимого, например File. Доступность других backend зависит от версии/редакции; БД metadata резервируется отдельно и согласованно.'),
('Blob reference','Связь metadata asset с идентичностью объекта в blob store. Потеря объекта оставляет логическую запись, которую нельзя успешно скачать.'),
