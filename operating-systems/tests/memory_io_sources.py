from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit, unquote
import json
import runpy

ROOT=Path(__file__).resolve().parents[1]
CHAPTERS=['os-04-address-spaces','os-10-page-tables-faults','os-11-allocation','os-12-working-set-reclaim','os-13-commit-swap-oom','os-18-open-files','os-19-filesystems','os-20-io-path','os-21-durability-recovery','os-22-storage-volumes','os-31-memory-io-observation']
VOID={'input','meta','link','br','hr','img','source','wbr','area','base','col','embed','param','track'}
class Document(HTMLParser):
 def __init__(self):super().__init__(convert_charrefs=True);self.stack=[];self.ids=set();self.links=[];self.text=[];self.h1=0
 def handle_starttag(self,tag,attrs):
  a=dict(attrs)
  if tag not in VOID:self.stack.append(tag)
  if 'id' in a:
   assert a['id']not in self.ids,('duplicate id',a['id']);self.ids.add(a['id'])
  if 'href'in a:self.links.append(a['href'])
  self.h1+=tag=='h1'
 def handle_startendtag(self,tag,attrs):
  self.handle_starttag(tag,attrs)
  if tag not in VOID:self.handle_endtag(tag)
 def handle_endtag(self,tag):
  assert self.stack and self.stack[-1]==tag,('unbalanced',tag,self.stack[-3:]);self.stack.pop()
 def handle_data(self,data):self.text.append(data)

def parse(path):
 d=Document();d.feed(path.read_text());assert not d.stack,(path,d.stack);return d

def main():
 chapter_ids={p.stem for p in (ROOT/'sources').glob('*.html')};pages={};links=0;pending=[]
 for name in CHAPTERS:
  d=parse(ROOT/'sources'/f'{name}.html');assert d.h1==1,name;pages[name]=d
  for href in d.links:
   u=urlsplit(href)
   if u.scheme:continue
   if not u.path:assert u.fragment in chapter_ids,(name,href)
   else:
    target=(ROOT/unquote(u.path)).resolve()
    # Other volume's index is generated by its owner, not by this source check.
    planned=target.name=='index.html'and(target.parent/'volume_config.py').is_file()and(target.parent/'build.py').is_file()
    if not target.is_file()and planned:pending.append(str(target.relative_to(ROOT.parent)))
    assert target.is_file()or planned,(name,href)
    if u.fragment and target.is_file():assert u.fragment in parse(target).ids,(name,href)
   links+=1
 diagrams=runpy.run_path(str(ROOT/'sources/diagrams_memory_io.py'))['DIAGRAMS'];ids=set()
 for item in diagrams:
  assert item['id']not in ids;ids.add(item['id']);assert item['chapter']in CHAPTERS
  assert(ROOT/'sources'/f"{item['chapter']}.html").read_text().count(item['insert_before'])==1,item['id']
  nodes={n['id']for n in item['nodes']};edges={e['id']for e in item['edges']};assert len(nodes)==len(item['nodes'])and len(edges)==len(item['edges'])
  assert all(e['from']in nodes and e['to']in nodes for e in item['edges'])
  for step in item['steps']:
   assert set(step['states'])==nodes;assert set(step['focus'])<=nodes;assert set(step['active'])<=edges
   assert all(isinstance(v,str)and v for v in step['states'].values());assert step['fields']and step['bands']
 lab=parse(ROOT/'labs/memory-io/index.html');assert lab.h1==1
 ref=runpy.run_path(str(ROOT/'sources/reference_memory_io.py'));terms=[t for t,_ in ref['GLOSSARY']];assert len(terms)==len(set(terms));assert ref['COMMANDS']==[]
 print(json.dumps({'result':'PASS','chapters':len(pages),'local_links':links,'diagrams':len(diagrams),'steps':sum(len(x['steps'])for x in diagrams),'glossary':len(terms),'pending_generated_destinations':sorted(set(pending)),'scope':'source structure, local destinations and exact insertion markers; no whole-book build/browser or editorial-quality claim'},ensure_ascii=False))
if __name__=='__main__':main()
