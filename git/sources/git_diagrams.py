"""Original build/CI step diagrams for the existing deep-sketch reader.

Pure data and pure helpers only: importing this module never reads files, runs
commands, opens network connections or changes the working tree. Hash prefixes
are computed from the explicitly defined educational inputs, not invented.
"""

import hashlib
import json


def _field(name, before, after, why):
    return dict(name=name, before=before, after=after, why=why)


def _step(title, explanation, actor, focus, active, states, *fields):
    return dict(
        title=title, explanation=explanation, actor=actor,
        focus=focus.split(), active=active.split(), states=states,
        fields=list(fields),
        bands=[dict(label=f['name'], value=f['after'], detail=f['why'])
               for f in fields],
    )


def _diagram(identifier, chapter, title, intro, assumptions, nodes, edges,
             steps, takeaway, sources, insert_before):
    return dict(
        id=identifier, volume='git', chapter=chapter, anchor=chapter,
        title=title, intro=intro, assumptions=assumptions,
        nodes=[dict(id=i, label=label, sub=sub) for i, label, sub in nodes],
        edges=[dict(id=i, **{'from': start, 'to': end}, label=label)
               for i, start, end, label in edges],
        steps=steps, takeaway=takeaway, sources=sources,
        insert_before=insert_before,
    )


def _sha(payload):
    return hashlib.sha256(payload).hexdigest()


_GREETING_SOURCE = (
    'import os\n'
    'print({"ru": "Привет", "en": "Hello"}[os.environ["LANGUAGE"]])\n'
).encode('utf-8')


def _key(language=None):
    """Return the full key of the explicitly specified teaching model."""
    description = dict(
        schema=1 if language is None else 2,
        action='greeting-v1',
        source_sha256=_sha(_GREETING_SOURCE),
        tool='python-model-v1',
    )
    if language is not None:
        description['language'] = language
    encoded = json.dumps(description, sort_keys=True, separators=(',', ':'),
                         ensure_ascii=True).encode('ascii')
    return _sha(encoded)


_BAD_KEY = _key()[:12]
_RU_KEY = _key('ru')[:12]
_EN_KEY = _key('en')[:12]
_RU_OUTPUT = _sha('Привет\n'.encode('utf-8'))[:12]
_EN_OUTPUT = _sha(b'Hello\n')[:12]


