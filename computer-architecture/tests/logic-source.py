"""Owned LOGIC source checks only. Does not run the shared book builder."""
from pathlib import Path
from html.parser import HTMLParser
import hashlib, json, re, runpy
ROOT = Path(__file__).resolve().parents[1]
CHAPTERS = ['ca-01-computer-model','ca-02-signals-gates','ca-03-numbers','ca-04-bytes-text-layout','ca-05-registers-clock','ca-07-instruction-encoding','ca-08-instruction-cycle','ca-09-control-stack-abi','ca-10-pipeline-dependencies','ca-11-speculation-retirement','ca-12-cpu-performance']
class Links(HTMLParser):
    def __init__(self): super().__init__(); self.links=[]
    def handle_starttag(self, tag, attrs):
        for k,v in attrs:
            if k in ('src','href') and v: self.links.append(v)
class Tables(HTMLParser):
    def __init__(self): super().__init__(); self.tables=[]; self.table=None; self.row=None; self.cell=None
    def handle_starttag(self, tag, attrs):
        if tag=='table': self.table=[]
        elif tag=='tr': self.row=[]
        elif tag in ('td','th'): self.cell=''
    def handle_data(self, data):
        if self.cell is not None: self.cell+=data
    def handle_endtag(self, tag):
        if tag in ('td','th') and self.cell is not None: self.row.append(self.cell.strip()); self.cell=None
        elif tag=='tr' and self.row is not None: self.table.append(self.row); self.row=None
        elif tag=='table' and self.table is not None: self.tables.append(self.table); self.table=None
checks=[]
def check(name, ok):
    checks.append(name)
    if not ok: raise AssertionError(name)
for name in CHAPTERS:
    p=ROOT/'sources'/f'{name}.html'; text=p.read_text(); parser=Links(); parser.feed(text)
    check(name+' has one heading',text.count('<h1>')==1)
    check(name+' no private absolute path',not re.search(r'/home/|file:///|localhost:|127\.0\.0\.1:',text))
    check(name+' no unpinned RISC-V current link','reference/isa/unpriv/' not in text)
    for link in parser.links:
        if re.match(r'^(?:https?:|#)',link): continue
        check(name+' local '+link,(ROOT/link.split('#')[0]).is_file())
diagrams=runpy.run_path(str(ROOT/'sources/diagrams_logic.py'))['DIAGRAMS']
check('diagram IDs unique',len({d['id'] for d in diagrams})==len(diagrams))
for d in diagrams:
    check(d['id']+' chapter owned',d['chapter'] in CHAPTERS)
    check(d['id']+' marker present',d['insert_before'] in (ROOT/'sources'/f'{d["chapter"]}.html').read_text())
    nodes={n['id'] for n in d['nodes']}; edges={e['id'] for e in d['edges']}
    check(d['id']+' unique node/edge IDs',len(nodes)==len(d['nodes']) and len(edges)==len(d['edges']))
    check(d['id']+' edge endpoints exist',all(e['from'] in nodes and e['to'] in nodes for e in d['edges']))
    for i,s in enumerate(d['steps']):
        check(d['id']+f' step{i} complete states',set(s['states'])==nodes)
        check(d['id']+f' step{i} references exist',set(s['focus'])<=nodes and set(s['active'])<=edges)
ref=runpy.run_path(str(ROOT/'sources/reference_logic.py'))
terms=[t[0] for t in ref['GLOSSARY']]
check('glossary names unique',len(set(terms))==len(terms))
check('alignment glossary delegated to MEMORY','Выравнивание' not in terms)
tables=Tables(); tables.feed((ROOT/'sources/ca-02-signals-gates.html').read_text())
gates=next(t for t in tables.tables if t[0]==['A','B','AND','OR','XOR','NAND'])
for row in gates[1:]:
    a,b,*actual=map(int,row)
    check(f'printed gate truth {a}/{b}',actual==[a&b,a|b,a^b,1-(a&b)])
adder=next(t for t in tables.tables if t[0]==['A','B','Cin','A+B+Cin','S','Cout'])
check('printed full adder has all eight distinct inputs',len({tuple(row[:3]) for row in adder[1:]})==8)
for row in adder[1:]:
    a,b,c,total,s,carry=map(int,row)
    check(f'printed full adder {a}/{b}/{c}',total==a+b+c and s==total%2 and carry==total//2)
check('UTF-8 example retains exactly A and Cyrillic Ya','<code>AЯ</code>' in (ROOT/'sources/ca-04-bytes-text-layout.html').read_text())
for p in (ROOT/'labs/logic').glob('*.html'):
    parser=Links(); parser.feed(p.read_text())
    for link in parser.links:
        if re.match(r'^(?:https?:|#)',link): continue
        target=(p.parent/link.split('#')[0]).resolve()
        # A common index is generated by the coordinator; all model scripts/styles must already exist.
        if target==ROOT/'index.html': continue
        check(p.name+' resource '+link,target.is_file())
    check(p.name+' offline scripts','https://' not in p.read_text() and 'http://' not in p.read_text())
print(json.dumps(dict(kind='owned-source-links-and-diagram-schema',passed=True,checks=len(checks),chapters=len(CHAPTERS),diagrams=len(diagrams),steps=sum(len(d['steps']) for d in diagrams),glossary=len(terms),not_checked='shared render, browser layout, prose clarity'),ensure_ascii=False))
