"""Original bounded scenarios: states are teaching data, not server responses."""


def make(identifier, chapter, marker, title, intro, assumptions, nodes, edges, rows):
    keys = [item[0] for item in nodes]
    steps = []
    for caption, explanation, actor, focus, active, values, field in rows:
        name, before, after, why = field
        assert len(values) == len(keys)
        steps.append(dict(title=caption, explanation=explanation, actor=actor,
                          focus=focus, active=active, states=dict(zip(keys, values)),
                          fields=[dict(name=name, before=before, after=after, why=why)],
                          bands=[dict(label=name, value=after, detail=why)]))
    return dict(id=identifier, volume='sonarqube', chapter=chapter, anchor=chapter,
                insert_before=marker, title=title, intro=intro, assumptions=assumptions,
                nodes=[dict(id=key, label=label, sub=sub) for key,label,sub in nodes],
                edges=[dict(id=key, **{'from':start,'to':end}, label=label) for key,start,end,label in edges],
                steps=steps)


